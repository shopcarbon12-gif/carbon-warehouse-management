/**
 * Regenerates lib/seo/full-pass/reference.generated.ts from the owner-approved
 * documents, so the worker (standalone build, no docs/ folder) carries them:
 *   docs/seo/PRODUCT-COPY-STANDARD.md   — the writing standard
 *   docs/seo/FULL-SEO-EXAMPLE-OUTPUT.json — two finished, approved products
 * Run after editing either file:  node scripts/gen-seo-full-reference.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const std = fs.readFileSync(path.join(root, "docs/seo/PRODUCT-COPY-STANDARD.md"), "utf8");
const ex = JSON.parse(fs.readFileSync(path.join(root, "docs/seo/FULL-SEO-EXAMPLE-OUTPUT.json"), "utf8"));
const out = `/* GENERATED by scripts/gen-seo-full-reference.mjs — do not edit by hand. */
export const COPY_STANDARD = ${JSON.stringify(std)};
export const EXAMPLE_OUTPUT = ${JSON.stringify(JSON.stringify(ex, null, 1))};
`;
fs.writeFileSync(path.join(root, "lib/seo/full-pass/reference.generated.ts"), out);
console.log("wrote lib/seo/full-pass/reference.generated.ts", out.length, "bytes");
